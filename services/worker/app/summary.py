from uuid import uuid4


def _base_json(mode: str) -> dict:
    return {
        "mode": mode,
        "citations": [{"page": 1, "block": "block-1"}],
        "confidence": {"overall": 0.8},
        "sections": [],
    }


def build_summary_payload(mode: str, safe_mode: bool) -> dict:
    payload = _base_json(mode)
    payload["safeMode"] = safe_mode
    payload["sections"] = [
        {"label": "Overview", "value": "Placeholder summary generated by worker stub."},
    ]
    return {
        "summaryId": str(uuid4()),
        "mode": mode,
        "safeMode": safe_mode,
        "json": payload,
    }
